/**
 * Compare instead of write, and fail if anything committed is stale.
 *
 * dune-board.svg and boardData.ts are committed, so they can drift from the
 * source export the moment someone hand-edits one or changes the export without
 * re-running. Mirrors `npm run verify:edge`, which guards the generated edge
 * bundle the same way.
 *
 * The spice deck is NOT checked: it is gitignored and regenerated by every
 * build, so there is no committed copy to be stale.
 */
const checkOnly = process.argv.includes('--check')
const stale = []

/** Write, or in check mode record whether what is on disk already matches. */
function emit(path, content) {
  if (!checkOnly) { writeFileSync(path, content); return }
  let onDisk = null
  try { onDisk = readFileSync(path, 'utf8') } catch { /* missing counts as stale */ }
  if (onDisk !== content) stale.push(path)
}

